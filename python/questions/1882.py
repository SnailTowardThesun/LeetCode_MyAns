"""
@file 1882.py
@brief LeetCode 1882. Process Tasks Using Servers（使用服务器处理任务）

@题目描述
    给你两个下标从 0 开始的整数数组 servers 和 tasks，长度分别为 n 和 m。
    servers[i] 是第 i 台服务器的权重，tasks[j] 是处理第 j 项任务所需要的
    时间（单位：秒）。第 j 项任务最早在第 j 秒开始处理。

    处理第 j 项任务时，为它分配一台空闲的服务器：
    - 若有多台空闲服务器，选权重最小的一台；权重相同则选下标最小的一台；
    - 若没有空闲服务器，则等待，出现空闲服务器后按上述规则尽可能早地处理，
      多项等待任务按下标递增顺序分配；同一时刻存在多台空闲服务器时，可以
      同时把多项任务分别分配给它们。
    每台服务器同一时刻只能处理一项任务；若在第 t 秒接到第 j 项任务，
    则在第 t + tasks[j] 秒恢复空闲（该时刻即可分配新任务）。

    返回数组 ans，其中 ans[j] 是第 j 项任务分配到的服务器下标。

    提示：
    - 1 <= n, m <= 2 * 10^5
    - 1 <= servers[i], tasks[j] <= 2 * 10^5

@示例
    示例 1：
    输入：servers = [3,3,2], tasks = [1,2,3,2,1,2]
    输出：[2,2,0,2,1,2]
    解释：
    - 第 0 秒，任务 0 分配给服务器 2（权重 2 最小），处理到第 1 秒；
    - 第 1 秒，服务器 2 空闲，任务 1 分配给服务器 2，处理到第 3 秒；
    - 第 2 秒，服务器 0/1 空闲且权重同为 3，任务 2 分配给下标小的服务器 0，
      处理到第 5 秒；
    - 第 3 秒，服务器 2 空闲，任务 3 分配给服务器 2，处理到第 5 秒；
    - 第 4 秒，任务 4 分配给唯一空闲的服务器 1，处理到第 5 秒；
    - 第 5 秒，三台服务器同时空闲，任务 5 分配给服务器 2，处理到第 7 秒。

    示例 2：
    输入：servers = [5,1,4,3,2], tasks = [2,1,2,4,5,2,1]
    输出：[1,4,1,4,1,3,2]
    解释：
    - 第 0 秒，任务 0 分配给服务器 1（权重 1 最小），处理到第 2 秒；
    - 第 1 秒，任务 1 分配给服务器 4（权重 2），处理到第 2 秒；
    - 第 2 秒，服务器 1/4 同时空闲，任务 2 分配给权重最小的服务器 1，
      处理到第 4 秒；
    - 第 3 秒，任务 3 分配给服务器 4（权重 2），处理到第 7 秒；
    - 第 4 秒，服务器 1 空闲，任务 4 分配给服务器 1，处理到第 9 秒；
    - 第 5 秒，空闲的只有 0/2/3 号服务器，任务 5 分配给权重最小的服务器 3，
      处理到第 7 秒；
    - 第 6 秒，任务 6 分配给服务器 2（权重 4），处理到第 7 秒。

@解题思路
    n、m 规模都到 2 * 10^5，且服务器/任务时间值很大，逐秒扫描或暴力找空闲
    服务器都会超时——用两个最小堆做"事件驱动"的模拟：

    1. 空闲堆 idle：存 (权重, 下标)，堆顶就是"权重最小、同权重下标最小"的
       服务器；
    2. 忙碌堆 busy：存 (释放时间, (权重, 下标))，堆顶是最早空闲的服务器；
    3. 按下标顺序处理任务，维护"当前时刻" now（任务 j 最早第 j 秒开始，若
       前面的任务在排队，now 可能已经超过 j，故先取 max(now, j)）：
       - idle 为空时，直接把 now 跳到 busy 堆顶的释放时间（下一个有服务器
         空出来的时刻），不做逐秒推进——这是复杂度的关键；
       - 把 busy 中所有释放时间 <= now 的服务器批量弹回 idle（同一时刻释放
         的多台一并回收，供排队的多个任务同时分配）；
       - 弹出 idle 堆顶即为最优服务器，结束时间 = now + tasks[j]，压入
         busy，记录分配结果。
    4. 返回 ret。

    时间复杂度 O((n + m) log n)（每台服务器在两堆间至多进出各一次，每次堆
    操作 O(log n)）；空间复杂度 O(n)。

来源：LeetCode
链接：https://leetcode.cn/problems/process-tasks-using-servers/description/
"""

from heapq import heapify, heappop, heappush


class Solution:
    def assignTasks(self, servers: list[int], tasks: list[int]) -> list[int]:
        ret = []
        idle = [(w, i) for i, w in enumerate(servers)]
        heapify(idle)

        busy = []
        now = 0

        for j, t in enumerate(tasks):
            now = max(now, j)
            if not idle:
                now = max(now, busy[0][0])
            # 回收当前时刻已经完成任务的所有服务器
            while busy and busy[0][0] <= now:
                bt = heappop(busy)
                heappush(idle, bt[1])

            s = heappop(idle)
            ret.append(s[1])
            heappush(busy, (now + t, s))

        return ret


